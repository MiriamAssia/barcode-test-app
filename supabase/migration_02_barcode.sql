-- העמודה עצמה. nullable בכוונה: אפשר להזין פריט גם בלי ברקוד
-- (למשל פריט שנשקל או שמגיע בלי אריזה מסומנת).
alter table public.items
  add column if not exists barcode text;

comment on column public.items.barcode is
  'הברקוד שעל אריזת הפריט, כפי שנסרק במסך הקליטה. ריק = לפריט אין ברקוד.';

-- מונע שני פריטים שונים עם אותו ברקוד. אינדקס חלקי: שורות שבהן
-- barcode ריק לא נספרות בכלל, ולכן אפשר להשאיר הרבה פריטים בלי ברקוד.
create unique index if not exists items_barcode_uidx
  on public.items (barcode)
  where barcode is not null;

